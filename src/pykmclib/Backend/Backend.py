class StdMapStringInt(dict):
    """A ``dict`` that mimics the SWIG ``std::map`` proxy API."""

    def size(self):
        """Return the number of entries (C++ style query)."""
        return len(self)


# ---------------------------------------------------------------------------
# Backend classes whose query methods returned SWIG container proxies upstream.
# The C++ layer returns plain lists/dicts; wrapping them here keeps the return
# types identical to what the upstream front end and tests expect.
# ---------------------------------------------------------------------------
class Configuration(_ExtConfiguration):
    def coordinates(self):
        return StdVectorCoordinate(_ExtConfiguration.coordinates(self))

    def atomIDCoordinates(self):
        return StdVectorCoordinate(_ExtConfiguration.atomIDCoordinates(self))

    def elements(self):
        return StdVectorStdVectorString(_ExtConfiguration.elements(self))

    def atomIDElements(self):
        return StdVectorString(_ExtConfiguration.atomIDElements(self))

    def types(self):
        return StdVectorTypeBucket(_ExtConfiguration.types(self))

    def atomID(self):
        return StdVectorInt(_ExtConfiguration.atomID(self))

    def movedAtomIDs(self):
        return StdVectorInt(_ExtConfiguration.movedAtomIDs(self))

    def recentMoveVectors(self):
        return StdVectorCoordinate(_ExtConfiguration.recentMoveVectors(self))

    def particlesPerType(self):
        return StdVectorInt(_ExtConfiguration.particlesPerType(self))

    def typeNames(self):
        return StdVectorString(_ExtConfiguration.typeNames(self))

    def possibleTypes(self):
        return StdMapStringInt(_ExtConfiguration.possibleTypes(self))


class Interactions(_ExtInteractions):
    def processes(self):
        return StdVectorProcessPtr(_ExtInteractions.processes(self))


