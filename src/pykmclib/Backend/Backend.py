"""Python facing bridge to the compiled C++ backend (pybind11).

The compiled extension is :mod:`pykmclib.Backend._backend`.  This module
re-exports it and restores the two things the upstream KMCLib front end (and
its test suite) relied on from the old SWIG wrappers:

* ``std::vector``/``std::map`` façade classes (``Backend.StdVectorInt(...)``,
  ``Backend.StdMapStringInt(...)``).  pybind11 accepts plain lists/dicts at the
  call boundary, so these are ordinary containers that also provide the few
  C++-style methods the front end uses (``push_back``, ``size``).
* Sequence semantics on values returned from C++: SWIG proxies compared equal
  to tuples/lists, so the façades implement element-wise ``__eq__`` and the
  classes whose results are compared in the upstream tests wrap their return
  values in the matching façade.
"""

from __future__ import annotations

import copy
import numbers

from ._backend import *  # noqa: F401,F403  (re-export the compiled classes)
from ._backend import Configuration as _ExtConfiguration
from ._backend import Interactions as _ExtInteractions
from ._backend import OnTheFlyMSD as _ExtOnTheFlyMSD


def _normalise(value):
    """Turn nested lists/tuples into nested lists for element-wise comparison."""
    if isinstance(value, (list, tuple)):
        return [_normalise(item) for item in value]
    return value


class _StdVector(list):
    """A ``list`` that mimics the SWIG ``std::vector`` proxy API."""

    #: Value used to pre-fill a vector constructed with a size.
    _fill = None

    def __init__(self, *args):
        if not args:
            super().__init__()
        elif len(args) == 1:
            self._init_from_one(args[0])
        elif len(args) == 2:
            count, value = args
            if not isinstance(count, numbers.Integral):
                raise TypeError("the first argument must be an integer size")
            super().__init__(self._repeated(int(count), value))
        else:
            raise TypeError(f"{type(self).__name__}() takes at most 2 arguments")

    def _init_from_one(self, value):
        if isinstance(value, numbers.Integral):
            super().__init__([self._fill] * int(value))
        else:
            super().__init__(value)

    def _repeated(self, count, value):
        # SWIG's std::vector(n, value) constructor fills with independent copies,
        # which the upstream tests rely on (each element is mutated separately).
        try:
            return [copy.deepcopy(value) for _ in range(count)]
        except Exception:
            return [value] * count

    #: C++ style append, as generated by SWIG.
    push_back = list.append

    def size(self):
        """Return the number of elements (C++ style query)."""
        return len(self)

    def __eq__(self, other):
        if isinstance(other, (list, tuple)):
            return _normalise(list(self)) == _normalise(list(other))
        return NotImplemented

    def __ne__(self, other):
        result = self.__eq__(other)
        if result is NotImplemented:
            return result
        return not result

    __hash__ = None


class StdVectorString(_StdVector):
    _fill = ""


class StdVectorInt(_StdVector):
    _fill = 0


